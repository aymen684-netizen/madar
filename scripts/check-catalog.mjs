import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context=vm.createContext({});vm.runInContext(fs.readFileSync('public/catalog-search.js','utf8'),context);
const {compile,normalize}=context.CatalogSearch,o={id:25544,name:'ISS (ZARYA)',omm:{OBJECT_ID:'1998-067A'}};
for(const query of ['٢٥٥٤٤','۲۵۵۴۴','NORAD 25544','iss zarya','1998–067A','1998 067a','  ISS  '])assert(compile(query)(o),query);
assert(compile('مَحَطّة الفَضاء')({id:1,name:'محطة الفضاء الدولية'}));
assert(compile('اقمار')({id:2,name:'أقمار'}));
assert(compile('رصد الأرض')(o,{program:'منظومة رصد الأرض'}));
assert(!compile('25544 STARLINK')(o),'all search terms must match');
assert(!compile('<img src=x>')(o),'markup is plain searchable text');
assert.equal(normalize('١۲٣—أرض'),'123 ارض');
console.log('PASS: Arabic/Persian NORAD digits, international identifiers, Arabic normalization, program names and multi-term search');
const hour=3600000,time=Date.UTC(2026,9,14),epoch=o=>o.epoch;
const records=[{id:1,name:'SAT 10',epoch:time-24*hour},{id:2,name:'SAT 2',epoch:time-72*hour},{id:3,name:'SAT 1',epoch:time+72*hour},{id:4,name:'SAT 3',epoch:time+72*hour+1},{id:5,name:'SAT 4',epoch:NaN}];
const ids=r=>Array.from(r.data,o=>o.id),refine=context.CatalogSearch.refine;
assert.deepEqual(ids(refine(records,{age:'recent',time},epoch)),[1]);
assert.deepEqual(ids(refine(records,{age:'within72',time},epoch)),[1,2,3]);
assert.deepEqual(ids(refine(records,{age:'old',time},epoch)),[4],'future and past epochs use absolute distance, unknown epochs are excluded');
const near=refine(records,{age:'within72',time},epoch);assert.equal(near.until,time+1);
assert.deepEqual(ids(refine(records,{age:'within72',time:near.until},epoch)),[1,3,4]);
assert.deepEqual(ids(refine(records,{sort:'newest'},epoch)),[4,3,1,2,5]);
assert.deepEqual(ids(refine(records,{sort:'name'},epoch)),[3,2,4,5,1]);
assert.deepEqual(ids(refine([...records].reverse(),{sort:'id'},epoch)),[1,2,3,4,5]);
assert.deepEqual(ids(refine(records,{},epoch)),[1,2,3,4,5]);
assert.deepEqual(records.map(o=>o.id),[1,2,3,4,5],'sorting must not mutate the source catalog');
console.log('PASS: inclusive 24/72-hour boundaries, future epochs, next-change time, numeric names, chronological sorting and immutable source order');
